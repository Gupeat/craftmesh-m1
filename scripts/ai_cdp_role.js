const CDP='http://127.0.0.1:9225';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const list=await (await fetch(CDP+'/json/list')).json();
 const target=list.find(t=>t.url.includes('/pages/ai.html'));
 if(!target) throw new Error('no target');
 const ws=new WebSocket(target.webSocketDebuggerUrl);
 let id=0; const pending=new Map();
 ws.onmessage=ev=>{const m=JSON.parse(ev.data); if(m.id){const p=pending.get(m.id); if(p){pending.delete(m.id); m.error?p.reject(new Error(JSON.stringify(m.error))):p.resolve(m.result);}}};
 await new Promise((res,rej)=>{ws.onopen=res;ws.onerror=rej;});
 const send=(method,params={})=>new Promise((res,rej)=>{const mid=++id;pending.set(mid,{resolve:res,reject:rej});ws.send(JSON.stringify({id:mid,method,params}));});
 await send('Runtime.enable'); await send('Page.enable');
 const ev=async expr=>{const r=await send('Runtime.evaluate',{expression:expr,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails).slice(0,300));return r.result.value;};
 await ev("localStorage.setItem('craftmesh-role','buyer')");
 await send('Page.reload',{ignoreCache:true});
 await sleep(3500);
 console.log('ROLE_TEXT',(await ev("document.querySelector('#roleStrip')?.innerText")||'').replace(/\s+/g,' ').slice(0,200));
 console.log('SCENARIO_DISABLED',await ev("document.querySelector('[data-action=run-scenario]').disabled"));
 console.log('KB_SUBMIT_DISABLED',await ev("document.querySelector('#knowledgeForm button[type=submit]').disabled"));
 console.log('KB_FORM_ALLOWED',await ev("document.querySelector('#knowledgeForm').dataset.allowed"));
 console.log('WF_RUN_BUTTONS',await ev("document.querySelectorAll('#workflowDetail button').length"));
 const before=await ev("document.querySelector('#scenarioBody')?.innerText.slice(0,60)");
 console.log('SCENARIO_BEFORE',(before||'').replace(/\s+/g,' '));
 console.log('TITLE',await ev('document.title'));
 await ev("localStorage.setItem('craftmesh-role','admin')");
 await send('Page.reload',{ignoreCache:true});
 await sleep(3000);
 console.log('RESTORED',await ev("localStorage.getItem('craftmesh-role')"));
 ws.close(); process.exit(0);
})().catch(e=>{console.error('FAILED',e.stack||e);process.exit(1);});